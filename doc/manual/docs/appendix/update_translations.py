"""Generate the Manual's translation sections from the bundled source.

ProperDocs renders virtual copies of the Markdown templates during builds.
For a standalone export, run this from the project root:

    python doc/manual/docs/appendix/update_translations.py --output-dir OUTPUT

Adapted from Robot Framework's `doc/userguide/translations.py` at revision
327ad2d38b0d468f03dbca97c7607b6b923730e0 (v7.5.1). Markdown templates,
escaping, links, and marker validation replace the reStructuredText output.
"""

import argparse
import html
import re
import sys
from pathlib import Path
from typing import cast

from markdown.extensions.toc import slugify

CURDIR = Path(__file__).resolve().parent
DOCS = CURDIR.parent
ROOT = CURDIR.parents[3]
TRANSLATIONS = CURDIR / "translations.md"
LOCALIZATION = CURDIR.parent / "syntax/data.md"
START_MARKER = "<!-- START GENERATED CONTENT -->"
END_MARKER = "<!-- END GENERATED CONTENT -->"
NOTICE = "<!-- Generated by appendix/update_translations.py. -->"


def load_languages():
    # Match the library generator: use this checkout, including during rebuilds.
    sys.path.insert(0, str(ROOT / "src"))
    for name in sorted(sys.modules):
        if name == "robot" or name.startswith("robot."):
            sys.modules.pop(name)
    from robot.api import Language

    return sorted(
        (lang for lang in Language.__subclasses__() if lang.code != "en"),
        # classproperty returns a string, but its descriptor is not typed.
        key=lambda lang: cast(str, lang.code),
    )


def escape_markdown(value):
    if value is None:
        return ""
    # Entities keep literal punctuation from becoming Markdown or table syntax.
    value = html.escape(value, quote=False)
    return re.sub(r"[\\`*_{}\[\]|]", lambda match: f"&#{ord(match[0])};", value)


class LanguageWrapper:

    def __init__(self, lang):
        self.lang = lang

    def __getattr__(self, name):
        value = getattr(self.lang, name)
        if isinstance(value, list):
            value = ", ".join(value)
        return escape_markdown(value)

    @property
    def new_in(self):
        new_in = re.search(r"(New in Robot Framework [\d.]+\.)", self.lang.__doc__)
        return ("\n" + new_in[1] + "\n") if new_in else ""


TEMPLATE = """\
## {lang.name} ({lang.code})
{lang.new_in}
#### Section headers

| Header | Translation |
|---|---|
| Settings | {lang.settings_header} |
| Variables | {lang.variables_header} |
| Test Cases | {lang.test_cases_header} |
| Tasks | {lang.tasks_header} |
| Keywords | {lang.keywords_header} |
| Comments | {lang.comments_header} |


#### Settings

| Setting | Translation |
|---|---|
| Library | {lang.library_setting} |
| Resource | {lang.resource_setting} |
| Variables | {lang.variables_setting} |
| Name | {lang.name_setting} |
| Documentation | {lang.documentation_setting} |
| Metadata | {lang.metadata_setting} |
| Suite Setup | {lang.suite_setup_setting} |
| Suite Teardown | {lang.suite_teardown_setting} |
| Test Setup | {lang.test_setup_setting} |
| Task Setup | {lang.task_setup_setting} |
| Test Teardown | {lang.test_teardown_setting} |
| Task Teardown | {lang.task_teardown_setting} |
| Test Template | {lang.test_template_setting} |
| Task Template | {lang.task_template_setting} |
| Test Timeout | {lang.test_timeout_setting} |
| Task Timeout | {lang.task_timeout_setting} |
| Test Tags | {lang.test_tags_setting} |
| Task Tags | {lang.task_tags_setting} |
| Keyword Tags | {lang.keyword_tags_setting} |
| Tags | {lang.tags_setting} |
| Setup | {lang.setup_setting} |
| Teardown | {lang.teardown_setting} |
| Template | {lang.template_setting} |
| Timeout | {lang.timeout_setting} |
| Arguments | {lang.arguments_setting} |


#### BDD prefixes

| Prefix | Translation |
|---|---|
| Given | {lang.given_prefixes} |
| When | {lang.when_prefixes} |
| Then | {lang.then_prefixes} |
| And | {lang.and_prefixes} |
| But | {lang.but_prefixes} |


#### Boolean strings

| True/False | Values |
|---|---|
| True | {lang.true_strings} |
| False | {lang.false_strings} |

"""

DEPRECATIONS = """\

#### Deprecations

| Old term | New term | Deprecated |
|---|---|---|
"""


def generate_docs(languages):
    for lang in languages:
        doc = TEMPLATE.format(lang=LanguageWrapper(lang))
        # Deprecation metadata was added in Robot Framework 7.5.
        if hasattr(lang, "deprecations") and lang.deprecations:
            doc += DEPRECATIONS
            for old, (new, version) in lang.deprecations.items():
                version = f"RF {escape_markdown(version)}" if version else ""
                doc += (
                    f"| {escape_markdown(old)} | {escape_markdown(new)} | {version} |\n"
                )
            doc += "\n"
        yield doc


def list_translations(languages):
    for lang in languages:
        title = f"{lang.name} ({lang.code})"
        anchor = slugify(title, "-")
        yield f"- [{escape_markdown(title)}](../appendix/translations.md#{anchor})"


def read_region(path):
    source = path.read_bytes().decode("utf-8")
    markers = []
    for marker in (START_MARKER, END_MARKER):
        matches = list(re.finditer(rf"^{re.escape(marker)}(?:\r?\n|$)", source, re.M))
        if source.count(marker) != 1 or len(matches) != 1:
            raise ValueError(
                f"{path}: expected exactly one '{marker}' on its own line. "
                "Add or correct the generated-content markers."
            )
        markers.append(matches[0])
    start, end = markers
    if start.end() > end.start():
        raise ValueError(f"{path}: move '{START_MARKER}' before '{END_MARKER}'.")
    return source, start.end(), end.start()


def render_region(region, content):
    source, start, end = region
    newline = "\r\n" if "\r\n" in source else "\n"
    generated = f"{NOTICE}\n\n" + "\n".join(content).rstrip("\n") + "\n\n"
    return source[:start] + generated.replace("\n", newline) + source[end:]


def render_pages(translations=TRANSLATIONS, localization=LOCALIZATION):
    # Validate both templates before generating either page.
    regions = [read_region(path) for path in (translations, localization)]
    languages = load_languages()
    content = [list(generate_docs(languages)), list(list_translations(languages))]
    targets = (Path("appendix/translations.md"), Path("syntax/data.md"))
    return {
        target: render_region(region, generated)
        for target, region, generated in zip(targets, regions, content, strict=True)
    }


def update_translations():
    import mkdocs_gen_files
    from mkdocs_gen_files.editor import FilesEditor

    # Outside a build, gen-files would write into docs_dir instead of virtual files.
    if Path(FilesEditor.current().directory).resolve().is_relative_to(DOCS):
        raise RuntimeError(
            "Translation generation requires an active ProperDocs build. "
            "Run 'properdocs build' or 'properdocs serve', or export with --output-dir."
        )
    pages = render_pages()
    for target, content in pages.items():
        with mkdocs_gen_files.open(target.as_posix(), "w", newline="") as file:
            file.write(content)
        mkdocs_gen_files.set_edit_path(target.as_posix(), target.as_posix())


def write_pages(output_dir, pages):
    output_dir = output_dir.resolve()
    if output_dir.is_relative_to(DOCS):
        raise ValueError(
            f"{output_dir}: choose an export directory outside the source docs folder "
            "to preserve the Markdown templates."
        )
    for target, content in pages.items():
        path = output_dir / target
        encoded = content.encode("utf-8")
        if not path.exists() or path.read_bytes() != encoded:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(encoded)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    write_pages(args.output_dir, render_pages())


# gen-files uses runpy.run_path(), which sets __name__ to '<run_path>'.
if __name__ == "__main__":
    main()
elif __name__ == "<run_path>":
    update_translations()
